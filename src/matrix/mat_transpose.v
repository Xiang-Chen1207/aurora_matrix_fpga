`timescale 1ns / 1ps
//////////////////////////////////////////////////////////////////////////////////
// 模块名称: mat_transpose (矩阵转置模块)
// 功能描述: 实现矩阵的转置运算 A(m×n) -> C(n×m)
// 数学原理: C[j][i] = A[i][j]，即行列互换
// 存储格式: 输入矩阵按行优先展开
//          A[i][j] 存储在 mat_A[(i*5+j)*8 +: 8]
//          C[j][i] 存储在 mat_C[(j*5+i)*8 +: 8]
// 支持规格: 最大支持5×5矩阵，每个元素8位无符号整数
//////////////////////////////////////////////////////////////////////////////////

module mat_transpose (
    //==================== 输入端口 ====================
    input  wire        clk,         // 系统时钟信号，上升沿触发
    input  wire        rst_n,       // 异步复位信号，低电平有效
    input  wire        start,       // 开始计算信号，高电平触发计算
    input  wire [2:0]  rows,        // 原矩阵行数 m，有效范围1-5
    input  wire [2:0]  cols,        // 原矩阵列数 n，有效范围1-5
    input  wire [199:0] mat_A,      // 输入矩阵A，展开为200位 (5×5×8bit = 200bit)

    //==================== 输出端口 ====================
    output reg  [199:0] mat_C,      // 转置结果矩阵C，维度变为 n×m
    output reg  [2:0]  result_rows, // 结果矩阵的行数 = 原矩阵的列数 cols
    output reg  [2:0]  result_cols, // 结果矩阵的列数 = 原矩阵的行数 rows
    output reg         done         // 计算完成标志，高电平表示计算完成
);

    //==================== 状态机状态定义 ====================
    localparam IDLE = 2'd0;         // 空闲状态：等待start信号
    localparam CALC = 2'd1;         // 计算状态：执行转置操作
    localparam DONE = 2'd2;         // 完成状态：输出结果，等待start撤销

    //==================== 内部寄存器定义 ====================
    reg [1:0] state;                // 当前状态寄存器，2位可表示3个状态
    reg [2:0] i, j;                 // 二维循环计数器，i为行索引，j为列索引

    //==================== 辅助函数：获取矩阵元素 ====================
    // 这个函数用于从扁平化的矩阵中提取指定位置的元素
    // 注意：此函数在当前实现中实际未被使用，保留作为参考
    function [7:0] get_element;
        input [199:0] matrix;       // 输入的扁平化矩阵
        input [2:0] row;            // 行索引
        input [2:0] col;            // 列索引
        reg [7:0] idx;              // 计算得到的位索引
        begin
            idx = (row * 5 + col) * 8;      // 计算线性地址的起始位
            get_element = matrix[idx +: 8]; // 提取8位元素
        end
    endfunction

    //==================== 主状态机：时序逻辑 ====================
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            //---------- 异步复位：初始化所有寄存器 ----------
            state <= IDLE;              // 状态机回到空闲状态
            done <= 1'b0;               // 清除完成标志
            i <= 3'd0;                  // 行索引清零
            j <= 3'd0;                  // 列索引清零
            mat_C <= 200'd0;            // 结果矩阵清零
            result_rows <= 3'd0;        // 结果行数清零
            result_cols <= 3'd0;        // 结果列数清零
        end else begin
            case (state)
                //========== IDLE状态：等待开始信号 ==========
                IDLE: begin
                    done <= 1'b0;           // 清除上一次的完成标志
                    if (start) begin        // 检测到start信号
                        state <= CALC;      // 转移到计算状态
                        i <= 3'd0;          // 初始化行索引
                        j <= 3'd0;          // 初始化列索引
                        mat_C <= 200'd0;    // 清空结果矩阵
                        // 关键：转置后维度互换
                        result_rows <= cols;// 结果行数 = 原矩阵列数
                        result_cols <= rows;// 结果列数 = 原矩阵行数
                    end
                end

                //========== CALC状态：执行转置操作 ==========
                CALC: begin
                    // 转置核心操作：C[j][i] = A[i][j]
                    // 原地址 A[i][j] = mat_A[(i*5+j)*8 +: 8]
                    // 目标地址 C[j][i] = mat_C[(j*5+i)*8 +: 8]
                    if (i < rows) begin
                        if (j < cols) begin
                            // 使用case语句展开所有可能的(i,j)组合
                            // 每个case将A[i][j]复制到C[j][i]的正确位置
                            case ({i, j})
                                //---------- i=0 的情况 ----------
                                // A[0][0] -> C[0][0]（对角线元素位置不变）
                                6'b000_000: mat_C[7:0]     <= mat_A[7:0];
                                // A[0][1] -> C[1][0]
                                // A的位置：(0*5+1)*8 = 8，即[15:8]
                                // C的位置：(1*5+0)*8 = 40，即[47:40]
                                6'b000_001: mat_C[47:40]   <= mat_A[15:8];
                                // A[0][2] -> C[2][0]
                                6'b000_010: mat_C[87:80]   <= mat_A[23:16];
                                // A[0][3] -> C[3][0]
                                6'b000_011: mat_C[127:120] <= mat_A[31:24];
                                // A[0][4] -> C[4][0]
                                6'b000_100: mat_C[167:160] <= mat_A[39:32];

                                //---------- i=1 的情况 ----------
                                // A[1][0] -> C[0][1]
                                6'b001_000: mat_C[15:8]    <= mat_A[47:40];
                                // A[1][1] -> C[1][1]（对角线元素）
                                6'b001_001: mat_C[55:48]   <= mat_A[55:48];
                                // A[1][2] -> C[2][1]
                                6'b001_010: mat_C[95:88]   <= mat_A[63:56];
                                // A[1][3] -> C[3][1]
                                6'b001_011: mat_C[135:128] <= mat_A[71:64];
                                // A[1][4] -> C[4][1]
                                6'b001_100: mat_C[175:168] <= mat_A[79:72];

                                //---------- i=2 的情况 ----------
                                // A[2][0] -> C[0][2]
                                6'b010_000: mat_C[23:16]   <= mat_A[87:80];
                                // A[2][1] -> C[1][2]
                                6'b010_001: mat_C[63:56]   <= mat_A[95:88];
                                // A[2][2] -> C[2][2]（对角线元素）
                                6'b010_010: mat_C[103:96]  <= mat_A[103:96];
                                // A[2][3] -> C[3][2]
                                6'b010_011: mat_C[143:136] <= mat_A[111:104];
                                // A[2][4] -> C[4][2]
                                6'b010_100: mat_C[183:176] <= mat_A[119:112];

                                //---------- i=3 的情况 ----------
                                // A[3][0] -> C[0][3]
                                6'b011_000: mat_C[31:24]   <= mat_A[127:120];
                                // A[3][1] -> C[1][3]
                                6'b011_001: mat_C[71:64]   <= mat_A[135:128];
                                // A[3][2] -> C[2][3]
                                6'b011_010: mat_C[111:104] <= mat_A[143:136];
                                // A[3][3] -> C[3][3]（对角线元素）
                                6'b011_011: mat_C[151:144] <= mat_A[151:144];
                                // A[3][4] -> C[4][3]
                                6'b011_100: mat_C[191:184] <= mat_A[159:152];

                                //---------- i=4 的情况 ----------
                                // A[4][0] -> C[0][4]
                                6'b100_000: mat_C[39:32]   <= mat_A[167:160];
                                // A[4][1] -> C[1][4]
                                6'b100_001: mat_C[79:72]   <= mat_A[175:168];
                                // A[4][2] -> C[2][4]
                                6'b100_010: mat_C[119:112] <= mat_A[183:176];
                                // A[4][3] -> C[3][4]
                                6'b100_011: mat_C[159:152] <= mat_A[191:184];
                                // A[4][4] -> C[4][4]（对角线元素）
                                6'b100_100: mat_C[199:192] <= mat_A[199:192];

                                default: ;  // 默认不操作
                            endcase

                            // 更新列索引
                            j <= j + 1'b1;
                        end else begin
                            // 当前行处理完毕，换到下一行
                            j <= 3'd0;          // 列索引归零
                            i <= i + 1'b1;      // 行索引加1
                        end
                    end else begin
                        // 所有元素处理完毕
                        state <= DONE;
                    end
                end

                //========== DONE状态：输出完成信号 ==========
                DONE: begin
                    done <= 1'b1;           // 设置完成标志
                    // 握手协议：等待start信号撤销
                    if (!start) begin
                        state <= IDLE;      // 返回空闲状态
                    end
                end

                //========== 默认状态：异常恢复 ==========
                default: state <= IDLE;     // 异常时回到空闲状态
            endcase
        end
    end

endmodule
